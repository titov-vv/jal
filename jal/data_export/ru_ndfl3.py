    def __init__(self, year, broker_as_income=False, only_dividends=False):
        template_path = JalSettings.path(JalSettings.PATH_TEMPLATES) + Setup.NDFL3_TEMPLATE_PATH
        template_file = template_path + os.sep + f"{year}.json"
        try:
            with open(template_file, 'r', encoding='utf-8') as json_template:
                self._tax_form = json.load(json_template)
        except FileNotFoundError:
            raise ValueError(self.tr("3-NDFL template not found for given year: ") + f"{year}")
        self._only_dividends = only_dividends
        self._broker_as_income = broker_as_income
        self._year = year
        self._parameters = TaxParameters('ru', year)
        self.currency = None
        self.account_name = ''
        self.broker_name = ''
        self.broker_iso_country = "000"
        self.stored_data = {
            "Дивиденды": {"dividend": self.append_dividend},
            "Акции": {
                "trade": self.append_stock_trade,
                "corporate_action": self.append_stock_trade
            },
            "Облигации": {"bond_trade": self.append_stock_trade, "bond_interest": self.append_bond_interest},
            "ПФИ": {"trade": self.append_derivative_trade},
            "Проценты": {"interest": self.append_other_income}
        }

    @staticmethod
    def tr(text):
        return QApplication.translate("Ru_NDFL3", text)

    # takes tax_report, generated by TaxesRus.prepare_tax_report(), and puts its data into tax form
    # Parameters contain auxiliary params of report
    def update_taxes(self, tax_report, parameters):
        try:
            self.currency = self.currencies[parameters['currency']]
        except KeyError:
            logging.error(self.tr("Currency is not supported for 3-NDFL: ") + parameters['currency'])
            return
        self.broker_name = parameters['broker_name']
        self.broker_iso_country = parameters['broker_iso_country']
        self.account_name = parameters.get('account_name', '')
        for section in [x for x in self.stored_data if x in tax_report]:   # the file's order, not the report's
            for template in self.stored_data[section]:
                for item in tax_report[section]:
                    if item['report_template'] == template:
                        self.stored_data[section][template](item)

    # The (income, expense) codes of a report row, read from the parameters by the row's kind
    def _codes(self, item) -> tuple:
        codes = self._parameters.code(item['kind'])
        if codes is None:
            raise ValueError(self.tr("No 3-NDFL code for this kind of income: ") + item['kind'])
        return codes

    # Save tax form in file format of russian tax software "Декларация 2.0" with given filename
    def save(self, filename):
        with open(filename, 'w', encoding='utf-8') as f:
            json.dump(self._tax_form, f, indent=2, ensure_ascii=False)

    def append_dividend(self, dividend):
        if self._broker_as_income:
            income_source = self.broker_name
            income_iso_country = self.broker_iso_country
            if income_iso_country == '000':
                logging.error(self.tr("Account country is not set, dividend isn't exported into 3-NDFL ") +
                              f"account='{self.account_name}', broker='{income_source}', asset='{dividend['symbol']}'")
                return
        else:
            income_source = f"Дивиденд от {dividend['symbol']} ({dividend['full_name']})"
            income_iso_country = dividend["country_iso"]
            if income_iso_country == '000':
                logging.error(self.tr("Country is not set for asset, dividend isn't exported into 3-NDFL ") +
                              f"asset='{dividend['symbol']}', isin='{dividend['isin']}', "
                              f"name='{dividend['full_name']}'")
                return
        dividend_record = {
          "SourseName": income_source,
          "CountryCode1": income_iso_country,
          "CountryCode2": self.broker_iso_country,
          "IncomeGetDate": datetime.fromtimestamp(dividend['payment_date'], tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%S"),
          "HoldDate": datetime.fromtimestamp(dividend['payment_date'], tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%S"),
          "CurrencyCode": self.currency['code'],
          "CurrencyName": self.currency['name'],
          "CurrencyExchange": float(dividend['rate'] * self.currency['multiplier']),
          "CurrencyUnits": self.currency['multiplier'],
          "CurrencyExchangeHoldDate": float(dividend['rate'] * self.currency['multiplier']),
          "CurrencyUnitsHoldDate": self.currency['multiplier'],
          "IncomeRoubleSum": float(dividend['amount_rub']),
          "TaxCurrencySum": float(dividend['tax']),
          "TaxRoubleSum": float(dividend['tax_rub']),
          "TaxRate": 0,
          "KIKIncomeType": 0,
          "KIKNum": "",
          "TaxKIKHoldRF": 0.0,
          "IncomeCod": self._codes(dividend)[0],
          "IncomeSum": float(dividend['amount']),
          "SubtractCod": self._codes(dividend)[1],
          "SubtractSum": 0.0
        }
        self._tax_form[FOREIGN_SECTION].append(dividend_record)

